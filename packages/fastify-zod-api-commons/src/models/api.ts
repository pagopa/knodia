import z from "zod";

export const API_Pagination = z
  .strictObject({
    limit: z.number().min(1).max(50).meta({ format: "int32" }),
    offset: z.number().min(0).meta({ format: "int32" }),
    total: z.number().min(0).meta({ format: "int32" }),
  })
  .meta({ id: "Pagination" });
export type API_Pagination = z.infer<typeof API_Pagination>;

export const API_PaginationQueryParams = z.strictObject({
  limit: z.coerce
    .number()
    .min(1)
    .max(50)
    .describe("Maximum number of items returned")
    .meta({ format: "int32" }),
  offset: z.coerce
    .number()
    .min(0)
    .describe("Pagination starting position")
    .meta({ format: "int32" }),
});
export type API_PaginationQueryParams = z.infer<
  typeof API_PaginationQueryParams
>;

const API_ProblemError = z
  .strictObject({
    detail: z
      .string()
      .max(4096)
      .meta({ example: "Parameter not valid", pattern: "^.{0,1024}$" })
      .describe(
        "A human readable explanation specific to this occurrence of the problem",
      ),
  })
  .meta({ id: "ProblemError" });

export const API_Problem = z
  .strictObject({
    code: z
      .string()
      .length(8)
      .meta({ example: "123-4567", pattern: "^[0-9]{3}-[0-9]{4}$" })
      .describe("Internal code of the error"),
    correlationId: z
      .string()
      .max(64)
      .meta({ example: "53af4f2d-0c87-41ef-a645-b726a821852b" })
      .describe("Unique identifier of the request"),
    errors: z.array(API_ProblemError),
    status: z
      .number()
      .min(100)
      .max(600)
      .meta({ example: 404, exclusiveMaximum: true, format: "int32" })
      .describe(
        "The HTTP status code generated by the origin server for this occurrence of the problem",
      ),
    title: z
      .string()
      .max(64)
      .meta({ example: "Service Unavailable", pattern: "^[ -~]{0,64}$" })
      .describe(
        "A short, summary of the problem type. Written in english and readable",
      ),
  })
  .meta({ id: "Problem" });
export type API_Problem = z.infer<typeof API_Problem>;
