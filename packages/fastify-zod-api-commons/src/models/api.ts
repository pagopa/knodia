import z from "zod";

/**
 * Wraps a Zod schema in an optional array query param that accepts both
 * a single value and an array. This is needed because query strings like
 * `?state=Active` send a string, while `?state=Active&state=Suspended`
 * send an array. See: https://github.com/turkerdev/fastify-type-provider-zod/issues/151
 */
export const arrayQueryParam = <T extends z.ZodType>(schema: T) =>
  z.preprocess((value) => {
    if (value === undefined) return undefined;
    return Array.isArray(value) ? value : [value];
  }, z.array(schema));

const API_ProblemError = z
  .strictObject({
    code: z.string().min(8).meta({
      description: "Internal code of the error",
      example: "123-4567",
      pattern: "^[0-9]{3}-[0-9]{4}$",
    }),
    detail: z.string().max(4096).meta({
      description:
        "A human readable explanation specific to this occurrence of the problem",
      example: "Parameter not valid",
      pattern: "^.{0,1024}$",
    }),
  })
  .meta({ id: "ProblemError" });

export const API_CorrelationId = z.uuid().meta({
  id: "CorrelationId",
});
export type API_CorrelationId = z.infer<typeof API_CorrelationId>;

export const API_Problem = z
  .strictObject({
    correlationId: API_CorrelationId.meta({
      description: "Unique identifier of the request",
      example: "53af4f2d-0c87-41ef-a645-b726a821852b",
    }),
    errors: z.array(API_ProblemError).min(1).optional(),
    status: z.number().min(100).max(600).meta({
      description:
        "The HTTP status code generated by the origin server for this occurrence of the problem",
      example: 404,
      exclusiveMaximum: true,
      format: "int32",
    }),
    title: z.string().max(64).meta({
      description:
        "A short, summary of the problem type. Written in english and readable",
      example: "Service Unavailable",
      pattern: "^[ -~]{0,64}$",
    }),
  })
  .meta({ id: "Problem" });
export type API_Problem = z.infer<typeof API_Problem>;
